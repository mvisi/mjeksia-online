#!/usr/bin/env node
// Regenerates constants/imageMap.ts from assets/contextImgs (Metro needs
// static `require` calls, so images cannot be looked up by name at runtime).
import { readdirSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const files = readdirSync(`${ROOT}assets/contextImgs`)
  .filter((f) => /\.(png|jpe?g|webp)$/i.test(f))
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

const lines = files.map((f) => `  "${f}": require("@/assets/contextImgs/${f}"),`);
writeFileSync(
  `${ROOT}constants/imageMap.ts`,
  `// Generated by scripts/generate-image-map.mjs — do not edit.\n\n` +
    `export const imageMap = {\n${lines.join("\n")}\n} as const;\n`,
);
console.log(`${files.length} images`);
